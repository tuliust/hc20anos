import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const ROOT = process.cwd();
const CHECK = process.argv.includes("--check");
const SOURCE_ROOTS = ["src", "api", "supabase/functions", "build"];
const EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".mts", ".cts"]);
const EXCLUDED = new Set(["src/lib/rpc.generated.ts"]);
const TS_OUTPUT = "src/lib/rpc.generated.ts";
const DOC_OUTPUT = "docs/30-contratos/RPCs-consumidas.generated.md";

function normalize(relativePath) {
  return relativePath.split(path.sep).join("/");
}

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory) {
  const absolute = path.join(ROOT, directory);
  if (!await exists(absolute)) return [];
  const entries = await readdir(absolute, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (["node_modules", "dist", ".git"].includes(entry.name)) continue;
    const relative = normalize(path.join(directory, entry.name));
    if (entry.isDirectory()) files.push(...await walk(relative));
    else if (entry.isFile() && EXTENSIONS.has(path.extname(entry.name)) && !EXCLUDED.has(relative)) files.push(relative);
  }
  return files;
}

function lineNumber(sourceFile, position) {
  return sourceFile.getLineAndCharacterOfPosition(position).line + 1;
}

function isRpcAccess(expression) {
  if (ts.isPropertyAccessExpression(expression)) return expression.name.text === "rpc";
  if (ts.isElementAccessExpression(expression)) {
    const argument = expression.argumentExpression;
    return Boolean(argument && ts.isStringLiteralLike(argument) && argument.text === "rpc");
  }
  return false;
}

function literalRpcName(node) {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  return null;
}

function collectAstUsages(file, content) {
  const kind = file.endsWith(".tsx") || file.endsWith(".jsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sourceFile = ts.createSourceFile(file, content, ts.ScriptTarget.Latest, true, kind);
  const usages = [];
  const dynamic = [];

  function visit(node) {
    if (ts.isCallExpression(node) && isRpcAccess(node.expression)) {
      const first = node.arguments[0];
      const name = first ? literalRpcName(first) : null;
      if (name) usages.push({ name, file, line: lineNumber(sourceFile, node.getStart(sourceFile)) });
      else dynamic.push({
        file,
        line: lineNumber(sourceFile, node.getStart(sourceFile)),
        expression: first ? first.getText(sourceFile).slice(0, 120) : "<sem argumento>",
      });
    }
    ts.forEachChild(node, visit);
  }

  visit(sourceFile);
  return { usages, dynamic };
}

function collectEmbeddedUsages(file, content, existing) {
  const usages = [];
  const pattern = /\.rpc\s*\(\s*(["'`])([a-zA-Z0-9_]+)\1/g;
  let match;
  while ((match = pattern.exec(content)) !== null) {
    const before = content.slice(0, match.index);
    const line = before.split("\n").length;
    const key = `${file}:${line}:${match[2]}`;
    if (!existing.has(key)) usages.push({ name: match[2], file, line });
  }
  return usages;
}

function pascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function gitValue(args, fallback) {
  try {
    return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim() || fallback;
  } catch {
    return fallback;
  }
}

function generateTypes(names, sourceCommit) {
  const aliases = names.map(name => {
    const alias = pascalCase(name);
    return [
      `export type ${alias}Args = RpcArgs<${JSON.stringify(name)}>;`,
      `export type ${alias}Returns = RpcReturns<${JSON.stringify(name)}>;`,
      `export type ${alias}Row = RpcRow<${JSON.stringify(name)}>;`,
    ].join("\n");
  }).join("\n\n");

  return `// Generated by npm run docs:generate-rpc-usage\n// Source commit: ${sourceCommit}\n// Do not edit manually.\n\nimport type { PublicRpcName, RpcArgs, RpcReturns, RpcRow } from "./rpc.types";\n\nexport const CONSUMED_RPC_NAMES = ${JSON.stringify(names, null, 2)} as const satisfies readonly PublicRpcName[];\n\nexport type ConsumedRpcName = (typeof CONSUMED_RPC_NAMES)[number];\n\n${aliases}\n`;
}

function generateDoc(names, usages, dynamic, sourceCommit, verifiedDate) {
  const usageRows = usages
    .sort((a, b) => a.name.localeCompare(b.name) || a.file.localeCompare(b.file) || a.line - b.line)
    .map(item => `| \`${item.name}\` | \`${item.file}:${item.line}\` | \`${pascalCase(item.name)}Args\` | \`${pascalCase(item.name)}Returns\` |`)
    .join("\n");
  const dynamicRows = dynamic.length
    ? dynamic.map(item => `| \`${item.file}:${item.line}\` | \`${item.expression.replaceAll("|", "\\|")}\` |`).join("\n")
    : "| — | nenhuma chamada dinâmica detectada |";

  return `---\nstatus: generated\nowner: tuliust\nlast_verified: ${verifiedDate}\nlast_verified_commit: ${sourceCommit}\ngeneration_command: npm run docs:generate-rpc-usage\nsource_files:\n  - src/\n  - api/\n  - supabase/functions/\n  - build/\n  - src/lib/rpc.types.ts\n  - scripts/generate-consumed-rpc-contracts.mjs\n---\n\n# RPCs efetivamente consumidas\n\n> Inventário gerado das chamadas \`.rpc(...)\` presentes no runtime e nas Functions. Não editar manualmente.\n\n## Resumo\n\n| Indicador | Resultado |\n|---|---:|\n| RPCs distintas | ${names.length} |\n| Ocorrências literais | ${usages.length} |\n| Chamadas dinâmicas | ${dynamic.length} |\n\nAs assinaturas são derivadas de \`Database["public"]["Functions"]\`. O arquivo \`src/lib/rpc.generated.ts\` faz o TypeScript validar cada nome contra a baseline reproduzida do Supabase.\n\n## Ocorrências\n\n| RPC | Consumidor | Alias de argumentos | Alias de retorno |\n|---|---|---|---|\n${usageRows || "| — | nenhuma | — | — |"}\n\n## Chamadas dinâmicas\n\n| Local | Expressão |\n|---|---|\n${dynamicRows}\n\nChamadas dinâmicas impedem a validação estática completa e fazem este gerador falhar.\n`;
}

async function assertOrWrite(relativePath, expected) {
  const absolute = path.join(ROOT, relativePath);
  if (CHECK) {
    const current = await readFile(absolute, "utf8").catch(() => null);
    if (current !== expected) throw new Error(`${relativePath} está ausente ou desatualizado`);
    return;
  }
  await mkdir(path.dirname(absolute), { recursive: true });
  await writeFile(absolute, expected, "utf8");
}

const files = (await Promise.all(SOURCE_ROOTS.map(walk))).flat().sort();
const usages = [];
const dynamic = [];
for (const file of files) {
  const content = await readFile(path.join(ROOT, file), "utf8");
  const ast = collectAstUsages(file, content);
  usages.push(...ast.usages);
  dynamic.push(...ast.dynamic);
  const existing = new Set(ast.usages.map(item => `${item.file}:${item.line}:${item.name}`));
  usages.push(...collectEmbeddedUsages(file, content, existing));
}

const uniqueUsages = [...new Map(usages.map(item => [`${item.file}:${item.line}:${item.name}`, item])).values()];
const names = [...new Set(uniqueUsages.map(item => item.name))].sort();
const sourceCommit = gitValue(["rev-parse", "HEAD"], "unknown");
const verifiedDate = gitValue(["show", "-s", "--format=%cs", "HEAD"], new Date().toISOString().slice(0, 10));

if (dynamic.length > 0) {
  const details = dynamic.map(item => `${item.file}:${item.line} (${item.expression})`).join("\n");
  throw new Error(`Chamadas RPC dinâmicas detectadas:\n${details}`);
}

await assertOrWrite(TS_OUTPUT, generateTypes(names, sourceCommit));
await assertOrWrite(DOC_OUTPUT, generateDoc(names, uniqueUsages, dynamic, sourceCommit, verifiedDate));

console.log(`${CHECK ? "Verificados" : "Gerados"}: ${names.length} contratos de RPC em ${uniqueUsages.length} ocorrências.`);
